// Writes the brand marks the footer shows for the Trust's profiles, copied from simple-icons
// (CC0, devDependency): public/icons/social.svg (one cached sprite, so pages carry only a
// <use> reference) and src/lib/social-icons.ts (the platforms it contains).
// Usage: node scripts/social-icons.mjs   (after upgrading simple-icons)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import * as si from "simple-icons";

const ICONS = {
  facebook: si.siFacebook,
  instagram: si.siInstagram,
  youtube: si.siYoutube,
  x: si.siX,
  whatsapp: si.siWhatsapp,
  telegram: si.siTelegram,
  threads: si.siThreads,
  pinterest: si.siPinterest,
};

const { version } = JSON.parse(readFileSync("node_modules/simple-icons/package.json", "utf8"));
const symbols = Object.entries(ICONS)
  .map(([k, icon]) => `<symbol id="${k}" viewBox="0 0 24 24"><path d="${icon.path}"/></symbol>`)
  .join("");
mkdirSync("public/icons", { recursive: true });
writeFileSync(
  "public/icons/social.svg",
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- simple-icons ${version} (CC0) -->${symbols}</svg>\n`,
);
writeFileSync(
  "src/lib/social-icons.ts",
  `// GENERATED by scripts/social-icons.mjs from simple-icons ${version} (CC0). Do not edit.\n` +
    `/** Brand marks in public/icons/social.svg (symbol ids, 24×24). */\n` +
    `export const SOCIAL_ICONS = ${JSON.stringify(Object.keys(ICONS))} as const;\n` +
    `export const SOCIAL_SPRITE = "/icons/social.svg";\n`,
);
console.log(`public/icons/social.svg: ${Object.keys(ICONS).length} icons from simple-icons ${version}`);
